CREATE PROCEDURE USP_ST_CARGA_CLIENTE 
AS
------------------------------
-- VERIFICA SE O SCHEMA EXISTE
------------------------------

IF OBJECT_ID ('ST_CLIENTES') IS NULL
BEGIN
CREATE TABLE ST_CLIENTES
(COD_CLIENTE NUMERIC (15), NOME VARCHAR(100), NOME_FANTASIA VARCHAR(60), COD_CLASSIFICACAO NUMERIC(15))
END

IF OBJECT_ID ('ST_CLIENTES_CLASSIFICACOES') IS NULL
BEGIN
CREATE TABLE ST_CLIENTES_CLASSIFICACOES 
(COD_CLASSIFICACAO NUMERIC (15), DESCRICAO VARCHAR(100))
END

IF OBJECT_ID ('ST_CLIENTES_ENDERECOS') IS NULL
BEGIN
CREATE TABLE ST_CLIENTES_ENDERECOS 
(ENTIDADE NUMERIC (15), CIDADE VARCHAR (100), UF CHAR(2))
END

IF OBJECT_ID ('ST_CLIENTES_ESTADOS') IS NULL
BEGIN
CREATE TABLE ST_CLIENTES_ESTADOS
(UF CHAR(2), ESTADO VARCHAR (60)) 
END 

------------------------------
-- LIMPA A STAGE
------------------------------
TRUNCATE TABLE ST_CLIENTES
TRUNCATE TABLE ST_CLIENTES_CLASSIFICACOES
TRUNCATE TABLE ST_CLIENTES_ENDERECOS
TRUNCATE TABLE ST_CLIENTES_ESTADOS 

---------------------------
-- POPULA STAGE AREA
---------------------------
INSERT INTO ST_CLIENTES (COD_CLIENTE, NOME, NOME_FANTASIA, COD_CLASSIFICACAO)
SELECT A.ENTIDADE, A.NOME, A.NOME_FANTASIA, A.CLASSIFICACAO_CLIENTE
FROM PBS_PROCFIT_DADOS..ENTIDADES A 

INSERT INTO ST_CLIENTES_CLASSIFICACOES (COD_CLASSIFICACAO, DESCRICAO)
SELECT B.CLASSIFICACAO_CLIENTE, B.DESCRICAO
FROM PBS_PROCFIT_DADOS..CLASSIFICACOES_CLIENTES B 

INSERT INTO ST_CLIENTES_ENDERECOS (ENTIDADE, CIDADE, UF)
SELECT ENTIDADE, CIDADE, ESTADO
FROM PBS_PROCFIT_DADOS..ENDERECOS

INSERT INTO ST_CLIENTES_ESTADOS (UF,ESTADO)
SELECT ESTADO, NOME 
FROM PBS_PROCFIT_DADOS..ESTADOS
