
MERGE  DIME_CLIENTE AS A
USING PBS_PROCFT_ST.DBO.VW_D_CLIENTES AS B
    ON A.COD_CLIENTE = B.COD_CLIENTE

WHEN MATCHED THEN UPDATE
SET NOME=B.NOME, NOME_FANTASIA=B.NOME_FANTASIA,CLASSIFICACAO=B.CLASSIFICACAO_CLIENTE,
CIDADE=B.CIDADE,UF =B.UF,ESTADO=B.ESTADO

WHEN NOT MATCHED BY TARGET THEN
    INSERT
   (COD_CLIENTE
    ,NOME, NOME_FANTASIA,CLASSIFICACAO,
CIDADE,UF ,ESTADO)
    VALUES(COD_CLIENTE,
    B.NOME,
 B.NOME_FANTASIA,
 B.CLASSIFICACAO_CLIENTE,
B.CIDADE, B.UF, B.ESTADO)
WHEN NOT MATCHED BY SOURCE THEN DELETE;

TRUNCATE TABLE DIME_CLIENTE
SELECT*FROM DIME_CLIENTE