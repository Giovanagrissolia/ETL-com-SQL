CREATE PROCEDURE USP_FULL_D_VENDEDOR

AS

IF OBJECT_ID ('D_VENDEDOR') IS NULL
BEGIN 

CREATE TABLE D_VENDEDOR (COD_VENDEDOR NUMERIC(15) PRIMARY KEY,
VENDEDOR VARCHAR (80))
END 

MERGE D_VENDEDOR D
USING [PBS_PROCFT_ST].[dbo].VW_D_VENDEDORES O
ON O.COD_VENDEDOR=D.COD_VENDEDOR
WHEN MATCHED THEN UPDATE
SET VENDEDOR=O.VENDEDOR
WHEN NOT MATCHED BY
TARGET THEN INSERT (COD_VENDEDOR, VENDEDOR)
VALUES (O.COD_VENDEDOR, O.VENDEDOR);
