MERGE D_EMPRESA D
USING PBS_PROCFT_ST.DBO.VW_D_EMPRESAS O ON O.COD_EMPRESA=D.COD_EMPRESA
WHEN MATCHED THEN UPDATE
SET NOME = O.NOME,
NOME_FANTASIA = O.NOME_FANTASIA

WHEN NOT MATCHED BY TARGET THEN INSERT
(COD_EMPRESA, NOME, NOME_FANTASIA)
VALUES
(O.COD_EMPRESA, O.NOME, O.NOME_FANTASIA);
