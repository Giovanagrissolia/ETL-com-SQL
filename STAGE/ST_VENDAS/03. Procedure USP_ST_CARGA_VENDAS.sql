ALTER PROCEDURE USP_ST_CARGA_VENDAS (@INCREMENTAL BIT)

/*
@INCREMENTAL =0 - CARGA FULL
@INCREMENTAL =1 -- CARGA INCREMENTAL
*/

AS

IF OBJECT_ID ('ST_VENDAS') IS NULL
BEGIN 

CREATE TABLE ST_VENDAS 
(COD_EMPRESA NUMERIC(15), COD_PRODUTO NUMERIC(15),COD_VENDEDOR NUMERIC(15), COD_CLIENTE NUMERIC(15), MOVIMENTO DATE, QUANTIDADE INT, VENDA_BRUTA MONEY, DESCONTO_TOTAL MONEY, VENDA_LIQUIDA MONEY, N_DOC NUMERIC(15))
END

TRUNCATE TABLE ST_VENDAS 
INSERT INTO ST_VENDAS (COD_EMPRESA, COD_PRODUTO,COD_VENDEDOR, COD_CLIENTE, MOVIMENTO, QUANTIDADE, VENDA_BRUTA, DESCONTO_TOTAL, VENDA_LIQUIDA, N_DOC)

SELECT EMPRESA, PRODUTO, VENDEDOR, CLIENTE, MOVIMENTO, QUANTIDADE, VENDA_BRUTA, DESCONTO+DESCONTO_NEGOCIADO AS DESCONTO, VENDA_LIQUIDA,
DOCUMENTO_NUMERO
FROM PBS_PROCFIT_DADOS..VENDAS_ANALITICAS 
WHERE MOVIMENTO> CASE WHEN @INCREMENTAL = 1 THEN (SELECT MAX(MOVIMENTO) FROM PBS_PROCFIT_DW..F_VENDAS)
ELSE '01/01/1900'
END
