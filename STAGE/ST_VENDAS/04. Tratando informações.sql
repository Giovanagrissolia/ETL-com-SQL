CREATE VIEW VW_F_VENDAS

AS


SELECT ISNULL (COD_EMPRESA,0) AS COD_EMPRESA
, ISNULL (COD_PRODUTO,0) AS COD_PRODUTO 
, ISNULL (COD_VENDEDOR, 0) AS COD_VENDEDOR
, ISNULL (COD_CLIENTE, 0) AS COD_CLIENTE
, MOVIMENTO
, QUANTIDADE
, VENDA_BRUTA
, DESCONTO_TOTAL
, VENDA_LIQUIDA
, ISNULL (N_DOC,0) AS N_DOC 
FROM ST_VENDAS